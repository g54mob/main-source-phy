	}

	public float GetDesiredAcceleration()
	{
		if (Mathf.Approximately(m_PinTargetAccelerationSeconds, 0f))
		{
			return float.MaxValue;
		}
		return Mathf.Abs(m_PinTargetVelocity / m_PinTargetAccelerationSeconds);
	}

