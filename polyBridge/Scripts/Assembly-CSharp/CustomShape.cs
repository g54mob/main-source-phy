	public void CreateVertsAndEdges()
	{
		m_Verts.Clear();
		m_Edges.Clear();
		for (int i = 0; i < m_PolygonCollider2D.points.Length; i++)
		{
			CustomShapeVert customShapeVert = CreateVert(m_PolygonCollider2D.points[i]);
			if (customShapeVert != null)
			{
				m_Verts.Add(customShapeVert);
				if (i > 0)
				{
					CustomShapeEdge customShapeEdge = new CustomShapeEdge();
					customShapeEdge.m_VertA = m_Verts[i - 1];
					customShapeEdge.m_VertB = m_Verts[i];
					m_Edges.Add(customShapeEdge);
				}
			}
		}
		CustomShapeEdge customShapeEdge2 = new CustomShapeEdge();
		customShapeEdge2.m_VertA = m_Verts[m_Verts.Count - 1];
		customShapeEdge2.m_VertB = m_Verts[0];
		m_Edges.Add(customShapeEdge2);
	}

	public void DestroyVertsAndEdges()
	{
		foreach (CustomShapeVert vert in m_Verts)
		{
			vert.gameObject.SetActive(value: false);
			UnityEngine.Object.Destroy(vert.gameObject);
		}
		m_Verts.Clear();
		m_Edges.Clear();
	}

