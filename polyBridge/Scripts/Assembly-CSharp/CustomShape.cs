		m_MaterialPropertyBlock.SetColor(ShaderVariables_SimpleLitCollidable.BUILD_MODE_TINT_SHADER_ID, (m_CollidesWithNodes || m_CollidesWithRoad) ? PostFX.m_Instance.m_BuildModeCollideTint : PostFX.m_Instance.m_BuildModeCustomShapeNoCollide);
