	private bool MakeMeshFromPolygonCollider()
	{
		int[] triangles = new TriangulatorBridges(m_PolygonCollider2D.points).Triangulate();
		Vector3[] array = new Vector3[m_PolygonCollider2D.points.Length];
		Vector2[] array2 = new Vector2[m_PolygonCollider2D.points.Length];
		for (int i = 0; i < array.Length; i++)
		{
			array[i] = new Vector3(m_PolygonCollider2D.points[i].x, m_PolygonCollider2D.points[i].y, 0f);
		}
		Vector3 vector = new Vector3(float.MaxValue, float.MaxValue, 0f);
		Vector3 vector2 = new Vector3(float.MinValue, float.MinValue, 0f);
		Vector3[] array3 = array;
		for (int j = 0; j < array3.Length; j++)
		{
			Vector3 vector3 = array3[j];
			if (vector3.x < vector.x)
			{
				vector.x = vector3.x;
			}
			if (vector3.y < vector.y)
			{
				vector.y = vector3.y;
			}
			if (vector3.x > vector2.x)
			{
				vector2.x = vector3.x;
			}
			if (vector3.y > vector2.y)
			{
				vector2.y = vector3.y;
			}
		}
		for (int k = 0; k < array.Length; k++)
		{
			Vector3 vector4 = array[k];
			array2[k].x = 0.1f * Mathf.Abs(vector4.x - vector.x);
			array2[k].y = 0.1f * Mathf.Abs(vector4.y - vector.y);
		}
		Mesh mesh = new Mesh();
		mesh.vertices = array;
		mesh.uv = array2;
		mesh.triangles = triangles;
		mesh.RecalculateNormals();
		mesh.RecalculateBounds();
		mesh.RecalculateNormals();
		bool flag = false;
		for (int l = 0; l < mesh.normals.Length; l++)
		{
			if (mesh.normals[l].z > 0f)
			{
				flag = true;
			}
		}
		if (flag)
		{
			return false;
		}
		m_MeshFilter.mesh = mesh;
		return true;
	}

	private void ExtrudeMesh(float distance)
	{
		Mesh mesh = new Mesh();
		MeshExtrusion.ExtrudeMesh(m_MeshFilter.mesh, mesh, distance);
		m_MeshRenderer.transform.localPosition = new Vector3(m_MeshRenderer.transform.localPosition.x, m_MeshRenderer.transform.localPosition.y, (0f - distance) / 2f);
		m_MeshFilter.mesh = mesh;
	}

