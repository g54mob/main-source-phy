	public void DestroyVert(CustomShapeVert vert)
	{
		if (!m_Verts.Contains(vert))
		{
			return;
		}
		m_Verts.Remove(vert);
		UnityEngine.Object.Destroy(vert.gameObject);
		CustomShapeEdge customShapeEdge = null;
		for (int i = 0; i < m_Edges.Count; i++)
		{
			if (m_Edges[i].m_VertA == vert)
			{
				customShapeEdge = m_Edges[i];
			}
		}
		for (int j = 0; j < m_Edges.Count; j++)
		{
			if (m_Edges[j].m_VertB == vert)
			{
				m_Edges[j].m_VertB = customShapeEdge.m_VertB;
			}
		}
		m_Edges.Remove(customShapeEdge);
	}

	public void DestroyPin(CustomShapePin pin)
	{
		if (m_Pins.Contains(pin))
		{
			m_Pins.Remove(pin);
		}
		UnityEngine.Object.Destroy(pin.gameObject);
	}

	public void DestroyAnchor(CustomShapeAnchor anchor)
	{
		BridgeJoint bridgeJoint = BridgeJoints.FindByGuid(anchor.m_BridgeJointGuid);
		if ((bool)bridgeJoint)
		{
			BridgeJoints.DestroyAnchors(new List<BridgeJoint> { bridgeJoint });
		}
		if (m_Anchors.Contains(anchor))
		{
			m_Anchors.Remove(anchor);
		}
		anchor.gameObject.SetActive(value: false);
		UnityEngine.Object.Destroy(anchor.gameObject);
	}

	public Vector3 GetNearestPosOnOutline(Vector3 worldPos)
	{
		Vector3 vector = new Vector3(float.MaxValue, float.MaxValue, 0f);
		foreach (CustomShapeEdge edge in m_Edges)
		{
			Vector3 start = new Vector3(edge.m_VertA.transform.position.x, edge.m_VertA.transform.position.y, 0f);
			Vector3 end = new Vector3(edge.m_VertB.transform.position.x, edge.m_VertB.transform.position.y, 0f);
			Vector3 vector2 = Utils.NearestPointOnLineSegment(start, end, worldPos);
			if (Vector2.Distance(vector2, worldPos) < Vector2.Distance(vector, worldPos))
			{
				vector = vector2;
			}
		}
		return vector;
	}

	public CustomShapeEdge GetNearestEdge(Vector3 worldPos)
	{
		Vector3 a = new Vector3(float.MaxValue, float.MaxValue, 0f);
		CustomShapeEdge result = null;
		foreach (CustomShapeEdge edge in m_Edges)
		{
			Vector3 vector = Utils.NearestPointOnLineSegment(edge.m_VertA.transform.position, edge.m_VertB.transform.position, worldPos);
			if (Vector3.Distance(vector, worldPos) < Vector3.Distance(a, worldPos))
			{
				a = vector;
				result = edge;
			}
		}
		return result;
	}

	public CustomShapeVert InsertVertOnEdge(CustomShapeEdge edge, Vector2 worldPos)
	{
		int num = m_Edges.IndexOf(edge);
		if (num < 0)
		{
			Debug.LogWarning("Coult not find edge on insertion");
			return null;
		}
		_ = edge.m_VertA;
		CustomShapeVert vertB = edge.m_VertB;
		int num2 = m_Verts.IndexOf(edge.m_VertA);
		CustomShapeVert customShapeVert = CreateVert(Vector3.zero);
		if ((bool)customShapeVert)
		{
			customShapeVert.transform.position = new Vector3(worldPos.x, worldPos.y, base.transform.position.z);
			m_Verts.Insert(num2 + 1, customShapeVert);
			edge.m_VertB = customShapeVert;
			CustomShapeEdge customShapeEdge = new CustomShapeEdge();
			customShapeEdge.m_VertA = customShapeVert;
			customShapeEdge.m_VertB = vertB;
			m_Edges.Insert(num + 1, customShapeEdge);
			customShapeVert.InverseScale(base.transform.localScale);
		}
		return customShapeVert;
	}

