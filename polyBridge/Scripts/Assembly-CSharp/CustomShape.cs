	public void MovePinsToFrontOfMesh()
	{
		foreach (CustomShapePin pin in m_Pins)
		{
			pin.transform.localPosition = new Vector3(pin.transform.localPosition.x, pin.transform.localPosition.y, m_MeshRenderer.transform.localPosition.z);
		}
	}

	public bool AddAnchor(Vector3 worldPos)
	{
		CustomShapeAnchor customShapeAnchor = CustomShapes.CreateAnchor(worldPos, m_AnchorsParent.transform, base.transform.localScale);
		if ((bool)customShapeAnchor)
		{
			m_Anchors.Add(customShapeAnchor);
			BridgeJoint bridgeJoint = CreateStaticJoint(customShapeAnchor.transform.position, customShapeAnchor.transform);
			customShapeAnchor.m_BridgeJointGuid = (bridgeJoint ? bridgeJoint.m_Guid : string.Empty);
			customShapeAnchor.m_SpriteRenderer.gameObject.SetActive(value: false);
			bridgeJoint.m_SandboxItem.SetOutlineDirty(dirty: true);
			return true;
		}
		return false;
	}

	public CustomShapePin AddPin(Vector3 worldPos)
	{
		CustomShapePin customShapePin = CustomShapes.CreatePin(worldPos, m_PinsParent.transform, base.transform.localScale);
		if ((bool)customShapePin)
		{
			m_Pins.Add(customShapePin);
			return customShapePin;
		}
		return null;
	}

	public void RemovePinsOutsideShape()
	{
		for (int num = m_Pins.Count - 1; num >= 0; num--)
		{
			CustomShapePin customShapePin = m_Pins[num];
			if (!OverlapsPoint(customShapePin.transform.position))
			{
				DestroyPin(customShapePin);
			}
		}
	}

	public void RemoveAnchorsOutsideShape()
	{
		for (int num = m_Anchors.Count - 1; num >= 0; num--)
		{
			CustomShapeAnchor customShapeAnchor = m_Anchors[num];
			if (!OverlapsPoint(customShapeAnchor.transform.position))
			{
				DestroyAnchor(customShapeAnchor);
			}
		}
	}

	public void Flip(bool flipped)
	{
		base.transform.localScale = new Vector3(flipped ? (0f - Mathf.Abs(base.transform.localScale.x)) : Mathf.Abs(base.transform.localScale.x), base.transform.localScale.y, base.transform.localScale.z);
		UpdateVisualScale();
		m_SandboxItem.SetOutlineDirty(dirty: true);
		MarkAllAnchorOutlinesDirty();
	}

	public void UpdateSpawnTransform()
	{
		m_SpawnPos = base.transform.position;
		m_SpawnRot = base.transform.rotation;
	}

	public CustomShape Duplicate(GameObject prefab, Vector3 offset)
	{
		CustomShape customShape = CustomShapes.CreateCustomShape(prefab, base.transform.position, base.transform.rotation);
		if (!customShape)
		{
			return null;
		}
		customShape.m_RotationDegrees = m_RotationDegrees;
		customShape.m_Mass = m_Mass;
		customShape.m_Bounciness = m_Bounciness;
		customShape.m_PinMotorStrength = m_PinMotorStrength;
		customShape.m_PinTargetVelocity = m_PinTargetVelocity;
		customShape.m_PinTargetAccelerationSeconds = m_PinTargetAccelerationSeconds;
		customShape.m_Color = m_Color;
		customShape.m_CollidesWithVehicles = m_CollidesWithVehicles;
		customShape.m_CollidesWithNodes = m_CollidesWithNodes;
		customShape.m_CollidesWithRamps = m_CollidesWithRamps;
		customShape.m_CollidesWithRoad = m_CollidesWithRoad;
		customShape.m_CollidesWithSplitNodes = m_CollidesWithSplitNodes;
		customShape.m_Behavior = m_Behavior;
		customShape.m_Thickness = m_Thickness;
		customShape.m_LowFriction = m_LowFriction;
		customShape.m_Texture = CustomShapeTextures.m_Instance.GetTextureFromId(m_Texture.m_ID);
		customShape.m_TextureTiling = m_TextureTiling;
		customShape.m_MeshId = m_MeshId;
		if (customShape.m_MeshId != CustomShapes.AUTO_GENERATED_MESH_ID)
		{
			customShape.UseCustomMesh(customShape.m_MeshId, m_MeshRenderer.transform.localPosition, 0f);
			customShape.m_CustomMeshScale = m_CustomMeshScale;
			customShape.m_CustomMesh.transform.localScale = m_CustomMeshScale;
			customShape.m_AutoGeneratedMesh.SetActive(value: false);
		}
		customShape.InitializeFromPointsArray(m_PolygonCollider2D.points);
		customShape.SetLocalScale(base.transform.localScale);
		DuplicateDynamicAnchors(customShape);
		DuplicatePins(customShape);
		customShape.transform.position += offset;
		customShape.UpdatePolygonShapes();
		customShape.EnableMeshRendering(on: false);
		return customShape;
	}

