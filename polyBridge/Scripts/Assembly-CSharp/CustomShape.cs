	public void RecalculatePivot()
	{
		Vector3 position = base.gameObject.transform.position;
		Vector3 zero = Vector3.zero;
		if (m_Pins.Count == 1)
		{
			zero = new Vector3(m_Pins[0].transform.position.x, m_Pins[0].transform.position.y, position.z);
		}
		else
		{
			Quaternion rotation = base.gameObject.transform.rotation;
			base.gameObject.transform.rotation = Quaternion.identity;
			Bounds bounds = new Bounds(m_Verts[0].transform.position, Vector3.zero);
			foreach (CustomShapeVert vert in m_Verts)
			{
				bounds.Encapsulate(vert.transform.position);
			}
			base.gameObject.transform.rotation = rotation;
			Vector3 vector = new Vector3(bounds.center.x, bounds.center.y, position.z);
			zero = rotation * (vector - position) + position;
			if (Mathf.Approximately((base.transform.position - zero).magnitude, 0f))
			{
				return;
			}
		}
		foreach (CustomShapeVert vert2 in m_Verts)
		{
			vert2.transform.localPosition = base.gameObject.transform.InverseTransformVector(vert2.transform.position - zero);
		}
		foreach (CustomShapePin pin in m_Pins)
		{
			pin.transform.localPosition = base.gameObject.transform.InverseTransformVector(pin.transform.position - zero);
		}
		foreach (CustomShapeAnchor anchor in m_Anchors)
		{
			anchor.transform.localPosition = base.gameObject.transform.InverseTransformVector(anchor.transform.position - zero);
		}
		base.gameObject.transform.position = new Vector3(zero.x, zero.y, (m_Anchors.Count > 0) ? 0f : position.z);
		RecalculateGridOffset();
		UpdateSpawnTransform();
		MarkAllAnchorOutlinesDirty();
		if (m_MeshId != CustomShapes.AUTO_GENERATED_MESH_ID)
		{
			Vector3 vector2 = base.gameObject.transform.position - position;
			m_MeshRenderer.transform.position -= vector2;
		}
		m_Dirty = true;
	}

	public void RecalculateGridOffset()
	{
		m_GridOffset = base.transform.position - GameGrid.SnapPosToGridForced(base.transform.position);
	}

	public void RebuildCollider()
	{
		Vector2[] array = new Vector2[m_Verts.Count];
		for (int i = 0; i < m_Verts.Count; i++)
		{
			array[i] = m_PolygonCollider2D.transform.InverseTransformPoint(m_Verts[i].transform.position);
		}
		m_PolygonCollider2D.SetPath(0, array);
		UpdatePolygonShapes();
	}

	public Vector2[] GetVerticesInWorldSpace()
	{
		Vector2[] array = new Vector2[m_Verts.Count];
		for (int i = 0; i < m_Verts.Count; i++)
		{
			array[i] = m_Verts[i].transform.position;
		}
		return array;
	}

	public void RebuildMesh()
	{
		MakeMeshFromPolygonCollider();
		ExtrudeMesh(m_Thickness);
		MovePinsToFrontOfMesh();
	}

	public void UseCustomMesh(string customMeshId, Vector3 localPosition, float enableMeshForSeconds)
	{
		m_StubBeingPreloadedLocalPosition = localPosition;
		m_StubBeingPreloadedEnableMeshForSeconds = enableMeshForSeconds;
		if (Prefabs.AsyncPrefabExists(customMeshId))
		{
			ObjectPreloadedCallback(customMeshId, string.Empty, success: true);
		}
		else
		{
			Prefabs.m_Instance.PreloadSingleAsset(customMeshId, string.Empty, ObjectPreloadedCallback);
		}
	}

	private void ObjectPreloadedCallback(string addressableName, string instanceID, bool success)
	{
		GameObject asyncPrefab = Prefabs.GetAsyncPrefab(addressableName);
		if (asyncPrefab == null)
		{
			Debug.LogWarningFormat("Could not find preloaded prefab with address " + addressableName);
			return;
		}
		if (m_CustomMesh != null)
		{
			UnityEngine.Object.Destroy(m_CustomMesh);
		}
		m_CustomMesh = UnityEngine.Object.Instantiate(asyncPrefab, base.transform);
		if (!(m_CustomMesh == null))
		{
			m_MeshRenderer.gameObject.SetActive(value: false);
			m_MeshRenderer = m_CustomMesh.GetComponentInChildren<MeshRenderer>();
			m_MeshRenderer.transform.localPosition = m_StubBeingPreloadedLocalPosition;
			m_CustomMesh.transform.localScale = m_CustomMeshScale;
			if (m_StubBeingPreloadedEnableMeshForSeconds > 0f)
			{
				m_DisableMeshRenderingTime = Time.realtimeSinceStartup + m_StubBeingPreloadedEnableMeshForSeconds;
			}
			else
			{
				m_MeshRenderer.gameObject.SetActive(GameStateManager.GetState() != GameState.SANDBOX);
			}
		}
	}

