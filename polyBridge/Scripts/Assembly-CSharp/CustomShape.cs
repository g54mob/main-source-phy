	private BridgeJoint CreateStaticJoint(Vector3 pos, Transform parent)
	{
		BridgeJoint bridgeJoint = BridgeJoints.CreateAnchor(pos, Utils.GenerateUniqueId());
		if (!bridgeJoint)
		{
			return null;
		}
		bridgeJoint.m_SandboxItem = SandboxItems.AddSandboxItemComponent(bridgeJoint.gameObject, SandboxItemType.ANCHOR);
		bridgeJoint.transform.parent = parent;
		return bridgeJoint;
	}

	private void MaybePlaySplashFX()
	{
		if (!m_PlayedSplashFX && !m_WasUnderWaterAtSimulationStart)
		{
			WaterBlock waterBlock = CenterPointUnderWater();
			if ((bool)waterBlock)
			{
				PlaySplashFX(waterBlock);
			}
		}
	}

	private void PlaySplashFX(WaterBlock waterBlock)
	{
		WaterSplash.Play(new Vector3(centerOfMassPosition.x, waterBlock.m_Height + 0.1f, base.transform.position.z), WaterSplashSize.BIG, waterBlock);
		m_PlayedSplashFX = true;
	}

	public WaterBlock CenterPointUnderWater()
	{
		if (m_PhysicsBodyIfDynamic == null || SandboxSettings.m_NoWater)
		{
			return null;
		}
		return WaterBlocks.PositionInWater(base.transform.position);
	}
