public static class KeyCodeConverter
{
	private static Dictionary<int, string> strings = new Dictionary<int, string>();

	private static Dictionary<string, KeyCode> codes = new Dictionary<string, KeyCode>();

	private static bool isInitialized = false;

	public static string ConvertString(string s)
	{
		switch (s)
		{
		case "Mouse0":
			return "M0";
		case "Mouse1":
			return "M1";
		case "Mouse2":
			return "M2";
		case "Mouse3":
			return "ScrollUp";
		case "Mouse4":
			return "ScrollDown";
		case "Mouse5":
			return "M5";
		case "Mouse6":
			return "M6";
		default:
			return s;
		}
	}

	public static bool GetKey(string key, out KeyCode keyCode)
	{
		key = ConvertString(key);
		if (!isInitialized)
		{
			Setup();
		}
		keyCode = KeyCode.None;
		if (!codes.ContainsKey(key))
		{
			return false;
		}
		keyCode = codes[key];
		return true;
	}

	public static string GetKey(KeyCode code)
	{
		if (!isInitialized)
		{
			Setup();
		}
		return strings[(int)code];
	}

